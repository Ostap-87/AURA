/**
 * Геометрия карты Китая для маршрута тура. Упрощённый контур материка
 * (около 90 точек, узнаваемый силуэт) и координаты городов, в которых
 * бывают поездки. Проекция линейная по долготе/широте — на этих широтах
 * соотношение осей близко к равноугольному.
 *
 * Новый город в таблице tour_days появится в списке компаний автоматически;
 * чтобы он получил точку на карте, добавьте координаты в CITY_COORDINATES.
 */

const LON_MIN = 73;
const LON_MAX = 135;
const LAT_MIN = 18;
const LAT_MAX = 54;

export const MAP_WIDTH = 640;
export const MAP_HEIGHT = 460;

export function project([lon, lat]: readonly [number, number]): [number, number] {
  const x = ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * MAP_WIDTH;
  const y = ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * MAP_HEIGHT;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

